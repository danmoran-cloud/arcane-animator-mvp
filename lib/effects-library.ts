export interface UnifiedEffectSettings {
  speed: number
  intensity: number
  density: number
  opacity: number
  glow: number
  colorA: string
  colorB: string
  angle: number
  turbulence: number
  scale: number
  pulseRate: number
  flicker: number
}

export interface ExpandedEffectDefinition {
  id: string
  name: string
  category: EffectCategory
  genreTags: GenreTag[]
  effectTags: EffectTypeTag[]
  description: string
  performance: PerformanceLevel
  defaultSettings: Partial<UnifiedEffectSettings>
  baseComponent: BaseEffectComponent
  defaultSize: { width: number; height: number }
}

