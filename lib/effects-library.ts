// Helper to get effects by category
export function getEffectsByCategory(category: EffectCategory): ExpandedEffectDefinition[] {
  return effectsLibrary.filter(e => e.category === category)
}

// Helper to search effects
export function searchEffects(query: string): ExpandedEffectDefinition[] {
  const lowerQuery = query.toLowerCase()
  return effectsLibrary.filter(e => 
    e.name.toLowerCase().includes(lowerQuery) ||
    e.description.toLowerCase().includes(lowerQuery) ||
    e.category.includes(lowerQuery) ||
    e.genreTags.some(t => t.toLowerCase().includes(lowerQuery)) ||
    e.effectTags.some(t => t.toLowerCase().includes(lowerQuery))
  )
}

// Helper to filter by tags
export function filterEffectsByTags(
  genreTags?: GenreTag[],
  effectTags?: EffectTypeTag[]
): ExpandedEffectDefinition[] {
  return effectsLibrary.filter(e => {
    const matchesGenre = !genreTags?.length || genreTags.some(t => e.genreTags.includes(t))
    const matchesEffect = !effectTags?.length || effectTags.some(t => e.effectTags.includes(t))
    return matchesGenre && matchesEffect
  })
}
